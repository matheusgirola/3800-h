"""Build the HTML5 edition with cross-reference pop-ups (variant D).

    python3 build/build_html.py            # -> 3800-h-tooltips.html

Reads the original 3800-h.htm, gives the first paragraph of every
numbered item an id (mapping/items.csv), and turns each row of the
mapping/refs-partN.csv files into a link plus pop-up. Parts whose
refs file does not exist yet get ids but no links.
"""

import csv
import html
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from structure import ROOT, load_source, parse  # noqa: E402

OUT = os.path.join(ROOT, "3800-h-tooltips.html")
PART_ROMAN = ["", "I", "II", "III", "IV", "V"]

FULL_TIP_WORDS = 200     # longer targets get an excerpt and no aria-describedby (decided 2026-10-05)
EXCERPT_WORDS = 60

