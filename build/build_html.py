TRANSNOTE = """
<div class="transnote">
<p>Transcriber’s note: references in the proofs, corollaries and
notes to earlier definitions, axioms, postulates, lemmas and
propositions have been made into internal links. Hovering over a
reference, or moving to it with the keyboard, shows the text it
refers to (for long notes, only an extract); following the
link goes to it. The text of the translation is unchanged.</p>
</div>
"""

LABEL_RE = re.compile(
    r"^(?:PROP\.\s+[IVXLC]+\.|DEFINITION\s+[IVXL]+\.|AXIOM\s+[IVX]+\.|LEMMA\s+[IVX]+\."
    r"|(?:Corollary|Coroll\.|Note|Explanation|Another [Pp]roof|Proof|Axiom|Definition)"
    r"(?:\s+[IVX]+)?\.?\s*—|[IVXL]+\.(?=\s))\s*")


def char_map(inner):
    """Plain-text characters of a paragraph with their source spans."""
    out = []
    i = 0
    while i < len(inner):
        c = inner[i]
        if c == "<":
            j = inner.index(">", i) + 1
            out.append((" ", i, j))
        elif c == "&":
            j = inner.index(";", i) + 1
            out.append((html.unescape(inner[i:j]), i, j))
        else:
            j = i + 1
            out.append((c, i, j))
        i = j
    res = []
    for ch, a, b in out:
        if ch.isspace():
            if res and res[-1][0] == " ":
                res[-1] = (" ", res[-1][1], b)
                continue
            ch = " "
        res.append((ch, a, b))
    while res and res[0][0] == " ":
        res.pop(0)
    while res and res[-1][0] == " ":
        res.pop()
    return res


def tip_label(it, source_part):
    label = it.label.replace("Coroll.", "Corollary")
    if it.kind == "emodef" and it.number:
        label = "Def. of the Emotions, " + label.rsplit(" ", 1)[1]
    if it.part != source_part:
        label = "Part %s, %s" % (PART_ROMAN[it.part], label)
    return label


def load_excerpts():
    """Hand-picked pop-up excerpts for long, often-cited targets."""
    path = os.path.join(ROOT, "mapping", "excerpts.csv")
    if not os.path.exists(path):
        return {}
    with open(path, newline="", encoding="utf-8") as f:
        return {r["target"]: r["excerpt"] for r in csv.DictReader(f) if r["target"].strip()}


EXCERPTS = load_excerpts()


def tip_text(it, paras, source_part):
    """(pop-up text, whether the target is short enough for describedby)."""
    body = paras[it.paras[0]]["text"]
    body = LABEL_RE.sub("", body, count=1)
    body = re.sub(r"\s?\[\d+\]", "", body)
    words = body.split()
    full = len(words) <= FULL_TIP_WORDS
    if not full and it.id in EXCERPTS:
        ex = EXCERPTS[it.id]
        pos = body.find(ex)
        if pos < 0:
            raise ValueError("excerpt for %s is not in its text" % it.id)
        body = ("" if pos == 0 else "… ") + ex + ("" if pos + len(ex) == len(body) else " …")
    elif not full:
        body = " ".join(words[:EXCERPT_WORDS]).rstrip(",;:—") + " …"
    return "%s. %s" % (tip_label(it, source_part), body), full


def load_refs():
    refs = {}
    for part in range(1, 6):
        path = os.path.join(ROOT, "mapping", "refs-part%d.csv" % part)
        if not os.path.exists(path):
            continue
        with open(path, newline="", encoding="utf-8") as f:
            for r in csv.DictReader(f):
                if r["flag"] in ("ok", "check") and r["target"]:
                    refs.setdefault(int(r["para"]), []).append(r)
    return refs


def render_paragraph(p, refs, byid, paras):
    inner = p["inner"]
    cmap = char_map(inner)
    plain = "".join(c for c, _, _ in cmap)
    assert plain == p["text"], (plain[:60], p["text"][:60])
    pieces, pos = [], 0
    for r in sorted(refs, key=lambda r: int(r["start"])):
        s, e = int(r["start"]), int(r["end"])
        assert plain[s:e] == r["text"], (r["text"], plain[s:e])
        a, b = cmap[s][1], cmap[e - 1][2]
        if a < pos:
            raise ValueError("overlapping links in %s: %s" % (r["source"], r["text"]))
        target = byid[r["target"]]
        tid = r["target"] if target.paras else ""
        tip, full = tip_text(target, paras, p["part"])
        desc = ' aria-describedby="%s"' % tid if full else ""
        pieces.append(inner[pos:a])
        pieces.append('<a class="ref" href="#%s"%s>%s</a><span class="tip" data-tip="%s" '
                      'aria-hidden="true"></span>'
                      % (tid, desc, inner[a:b], html.escape(tip, quote=True)))
        pos = b
    pieces.append(inner[pos:])
    return "".join(pieces)


HEADING_RE = re.compile(r'(?:<A NAME="(chap0\d)"></A>\s*)?<H([1-6])( ALIGN="center")?>(.*?)</H\2>', re.S)


def headings(out):
    """Give the headings a consistent outline (markup only; text unchanged).

    The original jumps levels (h2 -> h4) and uses h2-h4 for title-page
    lines. Title-page lines become styled paragraphs; each Part heading is
    an h2, its subtitle an h3, and its sections (Definitions, Axioms,
    Propositions ...) h3 in Part I, which has no subtitle, and h4 elsewhere.
    """
    state = {"part": 0}

    def rep(m):
        anchor, level, center, text = m.group(1), int(m.group(2)), m.group(3), m.group(4)
        idattr = ' id="%s"' % anchor if anchor else ""
        if anchor:
            state["part"] = int(anchor[-1])
            return '<h2 class="center"%s>%s</h2>' % (idattr, text)
        if state["part"] == 0:
            if level == 1:
                return '<h1>%s</h1>' % text
            return '<p class="titlepage tp%d">%s</p>' % (level, text)
        if center:                         # Part subtitle (Parts II-V)
            return '<h3 class="center">%s</h3>' % text
        lvl = 3 if state["part"] == 1 else 4
        return "<h%d>%s</h%d>" % (lvl, text, lvl)

    return HEADING_RE.sub(rep, out)


def build():
    src = load_source()
    paras, items = parse()
    byid = {it.id: it for it in items}
    refs = load_refs()

    # 1. paragraphs: ids and links (replace from the end to keep offsets)
    out = src
    for pi in range(len(paras) - 1, -1, -1):
        p = paras[pi]
        idattr = ' id="%s"' % p["item"] if p["first"] else ""
        if not idattr and pi not in refs:
            continue
        inner = render_paragraph(p, refs.get(pi, []), byid, paras) if pi in refs else p["inner"]
        cls = ' class="%s"' % p["cls"] if p["cls"] else ""
        out = out[:p["start"]] + "<p%s%s>%s</p>" % (idattr, cls, inner) + out[p["end"]:]

    # 2. markup: HTML 4.01 -> HTML5
    out = HEAD + out[out.index("<BODY>"):]
    out = out.replace("<BODY>", "<body>\n\n<main>", 1)
    out = out.replace("</BODY>", "</main>\n\n</body>", 1).replace("</HTML>", "</html>")
    out = headings(out)
    out = re.sub(r'<P CLASS="([a-z]+)">', r'<p class="\1">', out)
    out = out.replace("<P>", "<p>").replace("</P>", "</p>").replace("<BR>", "<br>")
    out = out.replace('<TABLE ALIGN="center" WIDTH="60%">', '<table class="toc">')
    out = out.replace('<TD ALIGN="left" VALIGN="top" WIDTH="20%">', "<td>")
    out = re.sub(r"<(/?)(TABLE|TR|TD)>", lambda m: "<%s%s>" % (m.group(1), m.group(2).lower()), out)
    out = out.replace('<A HREF="', '<a href="').replace("</A>", "</a>")
    out = out.replace("</table>", "</table>\n" + TRANSNOTE, 1)
    leftover = re.findall(r"<[A-Z][A-Z0-9]*\b[^>]*>", out)
    if leftover:
        raise ValueError("unconverted tags: %s" % sorted(set(leftover))[:10])
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    n = sum(len(v) for v in refs.values())
    print("%d links in %d paragraphs -> %s" % (n, len(refs), OUT))


if __name__ == "__main__":
    build()
